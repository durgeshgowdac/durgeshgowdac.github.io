"""Write characters.md, illustrations.md and scenes.md (repo root) from the registry, and fail if they drift from the code.

Checks, in order:
  1. every character in characters.json is a registered part, and its picture (home-theme PNG + SVG) exists;
  2. every registered part has an SVG in both themes, and art/parts holds nothing that is not registered;
  3. every scene component a page uses (AboutStripScene kinds, PageScene variants, *Strip / *Flight / *Sky / *Scene tags) has an entry
     in registry.tsx (or is covered by a cutaway below), and every scene and cutaway has its image.
Exit status 1 lists the problems; the markdown is still written so you can see what it would say.
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..'))
ART = os.path.join(REPO, 'art')   # the images live in art/; the three pages sit beside it at the repo root
data = json.load(open(os.path.join(HERE, '.build', 'art.json')))
chars = json.load(open(os.path.join(HERE, 'characters.json')))
problems = []
NOTE = "> **A note on the cast.** Fan tribute, strictly non-commercial. The characters belong to their creators and studios; the drawings are my own, made from scratch."
TH = {'light': 'Nature mode (light)', 'dark': 'Space mode (dark)'}
def anchor(s): return re.sub(r'[^\w\- ]', '', s.lower()).replace(' ', '-')
def exists(rel): return os.path.exists(os.path.join(REPO, rel))
def nav(me):
    pages = [('characters.md', 'Characters', 'who is in the scenery, and what they say'), ('illustrations.md', 'Illustrations', 'every drawing, by part'), ('scenes.md', 'Scenes', 'the compositions you scroll past')]
    return '*The art, in three pages:* ' + ' · '.join(f'**{t}**' if f == me else f'[{t}]({f})' for f, t, _ in pages)

parts = {p['id'] for g in data['groups'] for p in g['parts']}
home = {p['id']: p['theme'] for g in data['groups'] for p in g['parts'] if p['home']}

# ───────────────────────── 1 + 2: parts and characters ─────────────────────────
for g in chars['groups']:
    for m in g['members']:
        if m['part'] not in parts: problems.append(f"characters.json: {g['id']} / {m['name']} points at unregistered part '{m['part']}'"); continue
        if home[m['part']] != g['theme']: problems.append(f"characters.json: group {g['id']} is {g['theme']} but part {m['part']} lives in {home[m['part']]}")
        for ext in ('png', 'svg'):
            if not exists(f"art/parts/{g['theme']}/{m['part']}.{ext}"): problems.append(f"missing: art/parts/{g['theme']}/{m['part']}.{ext}")
    if not exists(f"art/characters/{g['id']}.png"): problems.append(f"missing contact sheet: art/characters/{g['id']}.png")
for g in data['groups']:
    for i in g['ids']:
        for t in ('light', 'dark'):
            if not exists(f'art/parts/{t}/{i}.svg'): problems.append(f'missing: art/parts/{t}/{i}.svg')
    for t in g['sheets']:
        if not exists(f"art/sheets/{g['id']}-{t}.svg"): problems.append(f"missing sheet: art/sheets/{g['id']}-{t}.svg")
for t in ('light', 'dark'):
    d = os.path.join(ART, 'parts', t)
    for f in sorted(os.listdir(d) if os.path.isdir(d) else []):
        if f.rsplit('.', 1)[0] not in parts: problems.append(f'stale file, no such part any more: art/parts/{t}/{f}')

# ───────────────────────── characters.md ─────────────────────────
def pic(part, theme, w, alt): return f'[<img src="art/parts/{theme}/{part}.png" width="{w}" alt="{alt}">](art/parts/{theme}/{part}.svg)'
cm = ['# Characters', '', nav('characters.md'), '',
      "Everyone drawn in the site's scenery, by world, with where they turn up and what they say. Each picture is a 1024 px PNG; click it for the vector. "
      "The drawings are the same parts listed in [illustrations.md](illustrations.md), so this page cannot drift from the code: "
      f"all {sum(len(g['members']) for g in chars['groups'])} pieces are regenerated by `bash tools/build.sh`.", '',
      "Nature pieces are drawn in the day palette and Space pieces in the night palette, so the Space characters look best on a dark background. "
      "Lines quoted are the ones the scenes actually speak.", '', '---', '']
seen_world = None
for g in chars['groups']:
    if g['world'] != seen_world:
        seen_world = g['world']; cm += [f'## {seen_world}', '']
        if seen_world == 'Element marks': cm += ['The four-emblem row at the foot of every Ch.02 hackathon card; the same sets spin as the loading indicator. Hover or tap a mark on the site for its hint.', '']
    cm += [f"### {g['title']}", '', f"![{g['title']} cast](art/characters/{g['id']}.png)", '']
    marks = g['id'].startswith('marks')
    cm += ['| Art | Mark | Where | Hint on the site |' if marks else '| Art | Character | Where they appear | What they do / say |', '|---|---|---|---|']
    for m in g['members']:
        cm.append(f"| {pic(m['part'], g['theme'], 90 if marks else 110, m['name'].split(' (')[0])} | **{m['name']}** | {m['where']} | {m['hint'] if marks else m['says']} |")
    for e in g.get('extra', []): cm.append(f"|  | **{e['name']}** | {e['where']} | {e['says']} |")
    cm += ['']
    if g.get('note'): cm += [g['note'], '']
    if g['id'] == 'marks-space': cm += ['Faction icons are Font Awesome Free brand icons (CC BY 4.0), in their faction colours.', '']
cm += ['---', '', '## Where each world lives', '', '| World | Scenes |', '|---|---|'] + [f'| {w} | {s} |' for w, s in chars['worlds']] + ['', '---', '', NOTE, '']
open(os.path.join(REPO, 'characters.md'), 'w').write('\n'.join(cm))

# ───────────────────────── illustrations.md ─────────────────────────
im = ['# Illustrations', '', nav('illustrations.md'), '',
      "Every illustration on the site, in one place. There are no stock images and no icon packs: each of these is an inline SVG component, hand-drawn in code and rendered here straight from the source, so this page cannot drift from the website.", '',
      "The site has two worlds, so most pieces appear twice: once in **Nature** (light) and once in **Space** (dark). Characters appear only in the world they live in. Nobody is to scale; a fox and a rocket have agreed to share a frame.", '',
      "The compositions you meet while scrolling (the strips, the backdrops, the page scenes) live in **[scenes.md](scenes.md)**; who is who, and what they say, is in **[characters.md](characters.md)**. This page is the parts they are built from.", '',
      '**Jump to:** ' + ' · '.join(f"[{g['title']}](#{anchor(g['title'])})" for g in data['groups']) + ' · [Scenes](scenes.md)', '']
for g in data['groups']:
    im += [f"## {g['title']}", '', g['blurb'], '']
    for t in g['sheets']:
        if len(g['sheets']) > 1: im += [f'**{TH[t]}**', '']
        im += [f"![{g['title']}, {t}](art/sheets/{g['id']}-{t}.svg)", '']
    links = ', '.join(f"[`{i}`](art/parts/{homeof}/{i}.svg)" for i in g['ids'] for homeof in [home[i]])
    im += [f"<details><summary>{len(g['ids'])} parts, as individual files</summary>", '', links, '', 'Each part also exists in both themes: `art/parts/light/` and `art/parts/dark/`.', '', '</details>', '']
im += ['---', '', NOTE, '']
open(os.path.join(REPO, 'illustrations.md'), 'w').write('\n'.join(im))

# ───────────────────────── 3: scenes ─────────────────────────
SCENES = data['scenes']; CUT = data['cutaways']
ids = {s['id'] for s in SCENES}; cids = {c['id'] for c in CUT}
# what each tag in app/ is covered by: a scene id, or `cutaway:<id>`
COVER = {
  'JourneyStrip': 'home-journey', 'ProfileFlight': 'about-profile-flight', 'DuelScene': 'page-contact',
  'HeroDuelStill': 'cutaway:duel-still', 'SpaceNotFoundScene': 'cutaway:space-404', 'HarryFlight': 'cutaway:harry-flight',
  'AppaFlight': 'cutaway:avatar-group', 'AvatarParty': 'cutaway:avatar-group', 'FlightScene': 'cutaway:avatar-group', 'AvatarCliffScene': 'cutaway:avatar-group',
  'QuidditchScene': 'about-catch', 'HackathonScene': 'about-hackathons',
  'ElementSpinner': None,   # the loading spinner is a set of element marks, shown in characters.md
}
IGNORE = {'CatchScene', 'Sky', 'TopSky', 'ContactStrip', 'ResultsStrip'}   # local helpers inside a covered scene, and text-only UI with "Strip" in its name
KIND = {'catch': 'about-catch', 'sky': 'about-inspiration', 'sports': 'about-sports', 'hackathons': 'about-hackathons'}
VARIANT = {'hero': 'page-hero', 'about': 'page-about', 'project': 'page-project', 'contact': 'page-contact'}
src = ''
for root, _, files in os.walk(os.path.join(REPO, 'app')):
    for f in files:
        if f.endswith('.tsx'): src += open(os.path.join(root, f)).read() + '\n'
used = set()
def want(sid, what):
    if sid in ids: used.add(sid)
    else: problems.append(f'{what} is used on a page but has no entry in tools/registry.tsx (expected scene id "{sid}")')
for k in re.findall(r'<AboutStripScene[^>]*\bkind="(\w+)"', src): want(KIND.get(k, f'about-{k}'), f'AboutStripScene kind="{k}"')
for m in re.finditer(r'<PageScene\b([^>]*)>', src):
    v = re.search(r'variant="(\w+)"', m.group(1)); v = v.group(1) if v else 'hero'
    want(VARIANT.get(v, f'page-{v}'), f'PageScene variant="{v}"')
for tag in sorted(set(re.findall(r'<(\w*(?:Scene|Strip|Flight|Sky|Still|Party|Spinner))\b', src))):
    if tag in ('AboutStripScene', 'PageScene') or tag in IGNORE: continue
    if tag not in COVER: problems.append(f'<{tag}> is used in app/ but has no entry in COVER (add it to registry.tsx, or to COVER in build_art.py if it is covered elsewhere)')
    elif COVER[tag] and not COVER[tag].startswith('cutaway:'): want(COVER[tag], f'<{tag}>')
for tag, v in COVER.items():
    if v and v.startswith('cutaway:') and v[8:] not in cids: problems.append(f'COVER[{tag}] points at unknown cutaway "{v[8:]}"')
    elif v and not v.startswith('cutaway:') and v not in ids: problems.append(f'COVER[{tag}] points at unknown scene "{v}"')
for s in SCENES:
    for t in s['themes']:
        if not exists(f"art/scenes/{s['id']}-{t}.png"): problems.append(f"image missing: art/scenes/{s['id']}-{t}.png")
for c in CUT:
    if not exists(f"art/scenes/{c['id']}-{c['theme']}.svg"): problems.append(f"cutaway missing: art/scenes/{c['id']}-{c['theme']}.svg")
for sid in sorted(ids - used): print(f'note: scene "{sid}" is in registry.tsx but no page uses it any more', file=sys.stderr)

sm = ['# Scenes', '', nav('scenes.md'), '',
      "The compositions you meet while scrolling: the strips that head each section, the backdrops behind the pages, and the Contact scene. Each one is the real component, photographed in a browser with the site's own stylesheet, so the sky, the ground and the colours are exactly what a visitor sees. On the live site they move and the characters have opinions; here each holds the still frame that reduced-motion visitors get.", '',
      "Strips are shown **with their sky** (the gradient the page paints behind them). Rebuild without it for transparent strips with `tools/build.sh scenes --no-bg`. The parts these are built from are in **[illustrations.md](illustrations.md)**; the people in them are in **[characters.md](characters.md)**.", '',
      '**Jump to:** ' + ' · '.join(f"[{s['title']}](#{anchor(s['title'])})" for s in SCENES) + ' · [Cutaways](#cutaways)', '']
for s in SCENES:
    sm += [f"## {s['title']}", '', f"*Where:* {s['where']}. {s['blurb']}", '']
    for t in s['themes']: sm += [f'**{TH[t]}**', '', f"![{s['title']}, {t}](art/scenes/{s['id']}-{t}.png)", '']
sm += ['## Cutaways', '', 'Tight crops of the moving parts of a scene, so the characters can be seen up close. Drawn from the same components as the scenes, on a plain backdrop.', '']
for c in CUT: sm += [f"### {c['title']}", '', f"*Where:* {c['where']}. {c['blurb']}", '', f"![{c['title']}](art/scenes/{c['id']}-{c['theme']}.svg)", '']
sm += ['---', '', NOTE, '']
open(os.path.join(REPO, 'scenes.md'), 'w').write('\n'.join(sm))

print(f"characters.md: {sum(len(g['members']) for g in chars['groups'])} characters | illustrations.md: {len(data['groups'])} groups, {len(parts)} parts | scenes.md: {len(SCENES)} scenes + {len(CUT)} cutaways")
if problems:
    print('\nPROBLEMS:'); [print(' -', p) for p in problems]; sys.exit(1)
print('coverage ok')